"""Trustworthy source-change capture (v3.1-alpha, PR-06).

``capture_change`` computes every digest itself: both tree digests come
from ``scan_tree``, every per-file byte digest is read from the
filesystem, and the unified diff is generated by this module — never
parsed from agent-reported output. An ``expected_before_digest`` anchors
the capture to the workspace's attested base; a mismatch means the base
moved under the agent (or the wrong workspace) and the capture refuses.
The agent cannot influence any digest field.
"""
from __future__ import annotations

import difflib
import hashlib
from pathlib import Path

from .contracts import ContractError, SourceChangeV1, canonical_digest
from .procedures import _utcnow
from .runner import scan_tree

_MAX_FILE_BYTES = 4 << 20
_MAX_FILES = 10_000


def _file_digests(root: Path) -> dict[str, tuple[str, int]]:
    """sha256 + size for every regular file under root (no symlinks)."""
    out: dict[str, tuple[str, int]] = {}
    root = Path(root)
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        relative = path.relative_to(root).as_posix()
        size = path.stat().st_size
        if size > _MAX_FILE_BYTES:
            raise ContractError(f"file exceeds capture bound: {relative}")
        out[relative] = (hashlib.sha256(path.read_bytes()).hexdigest(), size)
        if len(out) > _MAX_FILES:
            raise ContractError("workspace exceeds capture file bound")
    return out


def _read(root: Path, relative: str) -> bytes:
    return (root / relative).read_bytes()


def capture_change(
    before_dir: str | Path,
    after_dir: str | Path,
    *,
    attempt_id: str,
    worker_identity: str,
    expected_before_digest: str | None = None,
    now: str | None = None,
) -> tuple[SourceChangeV1, bytes]:
    """Capture a verified source change between two tree states.

    Returns ``(record, diff_bytes)``. All digests are computed here;
    ``expected_before_digest`` anchors to the workspace's attested base
    and a mismatch fails the capture.
    """
    before, after = Path(before_dir), Path(after_dir)
    for directory in (before, after):
        if not directory.is_dir():
            raise ContractError("capture directories must exist")
    before_tree = scan_tree(before).digest
    if expected_before_digest is not None and \
            expected_before_digest != before_tree:
        raise ContractError(
            "before_digest_mismatch: base moved or wrong workspace")
    after_tree = scan_tree(after).digest
    if before_tree == after_tree:
        raise ContractError("no_source_change: trees are identical")

    before_files = _file_digests(before)
    after_files = _file_digests(after)
    changes: list[dict] = []
    diff_parts: list[str] = []
    for path in sorted(set(before_files) | set(after_files)):
        old = before_files.get(path)
        new = after_files.get(path)
        if old == new:
            continue
        if old is None:
            kind, entry = "added", {"path": path, "kind": "added",
                                    "after_digest": new[0]}
            old_bytes, new_bytes = b"", _read(after, path)
        elif new is None:
            kind, entry = "removed", {"path": path, "kind": "removed",
                                      "before_digest": old[0]}
            old_bytes, new_bytes = _read(before, path), b""
        else:
            kind, entry = "modified", {"path": path, "kind": "modified",
                                       "before_digest": old[0],
                                       "after_digest": new[0]}
            old_bytes, new_bytes = _read(before, path), _read(after, path)
        changes.append(entry)
        try:
            old_text = old_bytes.decode("utf-8").splitlines(keepends=True)
            new_text = new_bytes.decode("utf-8").splitlines(keepends=True)
            diff_parts.extend(difflib.unified_diff(
                old_text, new_text,
                fromfile=f"a/{path}", tofile=f"b/{path}"))
        except UnicodeDecodeError:
            diff_parts.append(
                f"Binary files a/{path} and b/{path} differ\n")

    diff_bytes = "".join(diff_parts).encode("utf-8")
    diff_digest = hashlib.sha256(diff_bytes).hexdigest()
    record = SourceChangeV1(
        schema_version=1,
        change_id="change-" + canonical_digest("source_change", 1, {
            "before": before_tree, "after": after_tree,
            "diff": diff_digest, "attempt": attempt_id,
        })[:24],
        attempt_id=attempt_id,
        before_tree_digest=before_tree,
        after_tree_digest=after_tree,
        diff_digest=diff_digest,
        file_changes=tuple(changes),
        captured_at=now or _utcnow(),
        worker_identity=worker_identity,
    )
    return record, diff_bytes


def verify_capture(record: SourceChangeV1, diff_bytes: bytes) -> list[str]:
    """Re-verify a captured record against its diff bytes."""
    problems = []
    if not isinstance(record, SourceChangeV1):
        return ["not_a_source_change"]
    if hashlib.sha256(diff_bytes).hexdigest() != record.diff_digest:
        problems.append("diff_digest_mismatch")
    if not record.file_changes:
        problems.append("empty_change_set")
    return problems
